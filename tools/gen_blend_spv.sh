#!/usr/bin/env bash
# Regenerate helper/blend_spv.h from helper/shaders/blend.comp.
#
# Three compile-time format variants, because a Vulkan storage image's format is
# part of its GLSL type: rgba16f (HDR chain), rgba16unorm (SDR 16-bit multipass)
# and rgba8 (plain SDR chain). The helper picks the module by the work format.
set -euo pipefail
cd "$(dirname "$0")/.."

GLSLANG="${GLSLANG:-$(command -v glslang || command -v glslangValidator || true)}"
if [ -z "$GLSLANG" ]; then
    echo "no glslang/glslangValidator found" >&2
    exit 1
fi

src="helper/shaders/blend.comp"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

for spec in 16F:BLEND_16F=1 16UNORM:BLEND_16UNORM=1 8:NO_FMT=1; do
    name="${spec%%:*}"
    def="${spec#*:}"
    "$GLSLANG" "$src" -V "-D$def" -o "$tmp/$name.spv"
done

emit_array() { # emit_array <spv> <array-name>
    echo "static const uint32_t $2[] = {"
    od -An -tu4 -v "$1" | tr -s ' ' '\n' | grep -v '^$' | \
        awk '{printf "%s,", $0; if (++n % 12 == 0) printf "\n"} END {printf "\n"}'
    echo "};"
    echo "static const size_t ${2}Len = sizeof($2) / sizeof($2[0]);"
}

{
    echo "// Generated by tools/gen_blend_spv.sh from helper/shaders/blend.comp."
    echo "// Per-pass mix of input and model output; three chain-format variants."
    echo "#pragma once"
    echo "#include <cstdint>"
    emit_array "$tmp/16F.spv" kBlendSpv16F
    emit_array "$tmp/16UNORM.spv" kBlendSpv16UNorm
    emit_array "$tmp/8.spv" kBlendSpv8
} > helper/blend_spv.h
echo "wrote helper/blend_spv.h"
